import { writeFile } from 'node:fs/promises';
import { QAReleaseAWS } from './qa_release_aws.mjs';
const io = new QAReleaseAWS({cluster: 'mangorts-qa-cluster'});
const { Account } = await io.aws('sts', 'get-caller-identity');
if (Account !== '686458136219') throw new Error('Wrong QA account');
const { services } = await io.aws('ecs', 'describe-services', ['--cluster', io.c.cluster, '--services', 'mangorts-qa-backend']);
if (services.length !== 1) throw new Error('Expected one QA service');
const network = services[0].networkConfiguration.awsvpcConfiguration;
if (network.assignPublicIp !== 'DISABLED' || network.securityGroups.length !== 1) throw new Error('Unexpected QA network');
io.c.subnets = network.subnets;
io.c.security_group = network.securityGroups[0];
const { taskDefinition: source } = await io.aws('ecs', 'describe-task-definition', ['--task-definition', 'mangorts-qa-database-migration:19']);
const definition = await io.register(source, {image: process.env.MIGRATION_IMAGE_URI});
const result = await io.runTask(definition, ['-mode', 'audit']);
if (result.exitCode !== 0) throw new Error('Read-only audit failed');
for (const message of result.messages.filter(m => m.startsWith('MANGORTS_TABLE_COUNT='))) console.log(message);
await writeFile('qa-table-counts.json', JSON.stringify(result.messages.filter(m => m.startsWith('MANGORTS_TABLE_COUNT='))));
const prefix = 'MANGORTS_SCHEMA_INVENTORY_ITEM=';
const items = result.messages.filter(m => m.startsWith(prefix)).map(m => m.slice(prefix.length));
if (items.length < 100) throw new Error('Incomplete catalog export');
await writeFile('qa-schema-inventory.json', '[' + items.join(',\n') + ']' );
console.log(`Exported ${items.length} catalog definitions; no database rows exported.`);
for (const m of result.messages.filter(m => m.includes('read-only migration audit'))) console.log(m);
