import { writeFile } from 'node:fs/promises';
import { QAReleaseAWS } from './qa_release_aws.mjs';
const io = new QAReleaseAWS({cluster: 'mangorts-qa-cluster'});
const { Account } = await io.aws('sts', 'get-caller-identity');
if (Account !== '686458136219') throw new Error('Wrong QA account');
const { services } = await io.aws('ecs', 'describe-services', ['--cluster', io.c.cluster, '--services', 'mangorts-qa-backend']);
if (services.length !== 1) throw new Error('Expected one QA service');
const network = services[0].networkConfiguration.awsvpcConfiguration;
if (network.assignPublicIp !== 'DISABLED' || network.securityGroups.length !== 1) throw new Error('Unexpected QA network');
io.c.subnets = network.subnets;
io.c.security_group = network.securityGroups[0];
const { taskDefinition: source } = await io.aws('ecs', 'describe-task-definition', ['--task-definition', 'mangorts-qa-database-migration:19']);
const definition = await io.register(source, {image: process.env.MIGRATION_IMAGE_URI});
const repair = await io.runTask(definition, ['-mode', 'schema', '-schema', 'db/qa-approved-history-repair.sql']);
await writeFile('qa-history-repair-result.json', JSON.stringify(repair, null, 2));
if (repair.exitCode !== 0) throw new Error('Approved history repair failed; inspect preserved logs before retrying');
console.log('Approved history repair committed in QA.');
const result = await io.runTask(definition, ['-mode', 'plan']);
await writeFile('qa-history-repair-plan.json', JSON.stringify(result, null, 2));
const reports = result.messages.filter(m => m.startsWith('MANGORTS_MIGRATION_PLAN='));
if (reports.length !== 1) throw new Error('Expected one migration plan');
const plan = JSON.parse(reports[0].slice('MANGORTS_MIGRATION_PLAN='.length));
console.log(JSON.stringify(plan));
if (result.exitCode !== 0 || !plan.ready) throw new Error('Post-repair migration readiness failed');
