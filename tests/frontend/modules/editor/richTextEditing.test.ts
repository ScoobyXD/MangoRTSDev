import test from "node:test";
import assert from "node:assert/strict";
import { sanitizeAPIErrorMessage } from "../../../../frontend/src/modules/api/requestJSON.js";
import { EDITOR_DOCUMENT_BOTTOM_BUFFER_LINES, EDITOR_EMAIL_BODY_ATTRIBUTE, EDITOR_IMAGE_CLEAR_BREAK_ATTRIBUTE, EDITOR_LIST_ATTRIBUTE, EDITOR_RICH_TEXT_PREFIX, deserializeEditorDocumentHTML, editorBodyHasEmailContent, editorEmailDisplayDocument, getEditorLinkHrefForText, linkifyEditorPlainTextToHTML, normalizeEditorTableColumnWidths, sanitizeEditorDocumentHTML, serializeEditorBodyForEmailHTML } from "../../../../frontend/src/modules/editor/richTextEditing.js";
import { clampEditorImageVerticalOffset, createStandaloneImageClipboardHTML, editorAttachmentIDFromImageSource, editorAttachmentImageSource, getEditorImageFloatSideForVisualLeft, getEditorImageInlineOffsetForVisualLeft, getEditorImagePointerInteraction, getEditorImageStorageBudgetForDocumentBytes, isEditorAttachmentImageSource, isSafeEditorImageSource } from "../../../../frontend/src/modules/editor/editorImages.js";

test("editor rich text keeps a twenty-line bottom buffer", () => {
  assert.equal(EDITOR_DOCUMENT_BOTTOM_BUFFER_LINES, 20);
});

test("editor paste linkification turns plain URLs into safe visible links", () => {
  const html = linkifyEditorPlainTextToHTML("watch https://youtube.com/watch?v=abc now");

  assert.match(html, /<a href="https:\/\/youtube\.com\/watch\?v=abc"/);
  assert.match(html, /target="_blank"/);
  assert.match(html, /color: #0369a1/);
  assert.match(html, /text-decoration: underline/);
});

test("editor paste linkification preserves punctuation outside the URL", () => {
  const html = linkifyEditorPlainTextToHTML("open https://example.test/path.");

  assert.match(html, /href="https:\/\/example\.test\/path"/);
  assert.match(html, /<\/a>\./);
});

test("email serialization preserves editor line breaks and spacing", () => {
  const html = serializeEditorBodyForEmailHTML(`${EDITOR_RICH_TEXT_PREFIX}First line\n  1. indented\n\nNext block`);

  assert.match(html, new RegExp(`${EDITOR_EMAIL_BODY_ATTRIBUTE}="true"`));
  assert.match(html, /white-space:pre-wrap/);
  assert.match(html, /First line<br>  1\. indented<br><br>Next block/);
});

test("email display documents preserve Mango-authored body structure", () => {
  const html = serializeEditorBodyForEmailHTML(`${EDITOR_RICH_TEXT_PREFIX}First line\n  1. indented`);
  const documentHTML = editorEmailDisplayDocument(html);

  assert.match(documentHTML, new RegExp(`${EDITOR_EMAIL_BODY_ATTRIBUTE}="true"`));
  assert.match(documentHTML, /white-space:pre-wrap!important/);
  assert.match(documentHTML, /First line<br>  1\. indented/);
});

test("email serialization keeps plain text links and explicit line breaks", () => {
  const html = serializeEditorBodyForEmailHTML("Hello\n  https://example.test/path.");

  assert.match(html, /Hello<br>  <a href="https:\/\/example\.test\/path"/);
  assert.match(html, /<\/a>\./);
});

test("email serialization preserves rich lists and indented blocks", () => {
  const html = serializeEditorBodyForEmailHTML(`${EDITOR_RICH_TEXT_PREFIX}<ul ${EDITOR_LIST_ATTRIBUTE}="bullet"><li>One</li><li>Two</li></ul><div style="margin-left: 40px;">Indented</div>`);

  assert.match(html, /<ul data-mango-editor-list="bullet"><li>One<\/li><li>Two<\/li><\/ul>/);
  assert.match(html, /<div style="margin-left: 40px;">Indented<\/div>/);
});

test("editor link href normalization supports appended URL characters", () => {
  assert.equal(getEditorLinkHrefForText("www.example.test/path"), "https://www.example.test/path");
  assert.equal(getEditorLinkHrefForText("not a link"), null);
});

test("plain stored editor documents are escaped before becoming rich HTML", () => {
  const html = deserializeEditorDocumentHTML("<script>alert(1)</script> https://example.test");

  assert.match(html, /&lt;script&gt;alert\(1\)&lt;\/script&gt;/);
  assert.match(html, /<a href="https:\/\/example\.test\/"/);
});

test("api error sanitizer does not render upstream HTML documents", () => {
  const message = sanitizeAPIErrorMessage(403, "Forbidden", "<!DOCTYPE HTML><html><head><title>ERROR: The request could not be satisfied</title></head><body>Generated by cloudfront</body></html>");

  assert.equal(message, "Request failed (403 Forbidden). Received an HTML error page from the API/CDN.");
  assert.doesNotMatch(message, /DOCTYPE|<html|cloudfront/i);
});

test("editor sanitizer collapses nested font-size wrappers to the final size", () => {
  const html = sanitizeEditorDocumentHTML('<span style="font-size: 14px;"><span style="font-size: 15px;"><span style="font-size: 16px;">nice</span></span></span>');

  assert.equal(html, '<span style="font-size: 16px;">nice</span>');
});

test("editor sanitizer preserves image clear breaks", () => {
  const html = sanitizeEditorDocumentHTML(`<br ${EDITOR_IMAGE_CLEAR_BREAK_ATTRIBUTE}="true" style="clear: both;">after`);

  assert.match(html, new RegExp(`<br ${EDITOR_IMAGE_CLEAR_BREAK_ATTRIBUTE}="true"(?: clear="all")? style="clear: both;?">after`));
});

test("editor table width normalization keeps columns bounded and proportional", () => {
  const exact = normalizeEditorTableColumnWidths([20, 30, 50], 3);
  const squeezed = normalizeEditorTableColumnWidths([1, 1, 98], 3);

  assert.deepEqual(exact.map((value) => Math.round(value)), [20, 30, 50]);
  assert.equal(Math.round(squeezed.reduce((sum, value) => sum + value, 0)), 100);
  assert.ok(squeezed.every((value) => value >= 4));
});

test("editor image source sanitizer only accepts raster data images", () => {
  assert.equal(isSafeEditorImageSource("data:image/png;base64,iVBORw0KGgo="), true);
  assert.equal(isSafeEditorImageSource("data:image/svg+xml;base64,PHN2Zy8+"), false);
  assert.equal(isSafeEditorImageSource("https://example.test/image.png"), false);
});

test("editor attachment images use durable reference sources instead of data urls", () => {
  const src = editorAttachmentImageSource(" attachment-1 ");

  assert.equal(src, "mango-attachment:attachment-1");
  assert.equal(isEditorAttachmentImageSource(src), true);
  assert.equal(isSafeEditorImageSource(src), false);
  assert.equal(editorAttachmentIDFromImageSource(src), "attachment-1");
  assert.equal(editorAttachmentIDFromImageSource("mango-attachment:attachment%20one"), "attachment one");
});

test("an attachment-backed screenshot counts as email body content without text", () => {
  const body = `${EDITOR_RICH_TEXT_PREFIX}<span data-mango-editor-image="true" data-mango-editor-attachment-id="attachment-1"><img src="mango-attachment:attachment-1" alt=""></span>`;
  assert.equal(editorBodyHasEmailContent(body), true);
  assert.equal(editorBodyHasEmailContent(`${EDITOR_RICH_TEXT_PREFIX}<div><br></div>`), false);
});

test("standalone image clipboard HTML uses safe raster sources and escaped alt text", () => {
  const html = createStandaloneImageClipboardHTML("data:image/png;base64,iVBORw0KGgo=", 'Screen "one" <copy>');

  assert.equal(html, '<img src="data:image/png;base64,iVBORw0KGgo=" alt="Screen &quot;one&quot; &lt;copy&gt;">');
  assert.equal(createStandaloneImageClipboardHTML("https://example.test/image.png"), "");
});

test("editor image pointer zones support every edge and corner", () => {
  assert.deepEqual(getEditorImagePointerInteraction(200, 120, 4, 60), { kind: "resize", horizontal: -1, vertical: 0 });
  assert.deepEqual(getEditorImagePointerInteraction(200, 120, 10, 60), { kind: "drag" });
  assert.deepEqual(getEditorImagePointerInteraction(200, 120, 196, 60), { kind: "resize", horizontal: 1, vertical: 0 });
  assert.deepEqual(getEditorImagePointerInteraction(200, 120, 100, 4), { kind: "resize", horizontal: 0, vertical: -1 });
  assert.deepEqual(getEditorImagePointerInteraction(200, 120, 100, 116), { kind: "resize", horizontal: 0, vertical: 1 });
  assert.deepEqual(getEditorImagePointerInteraction(200, 120, 4, 4), { kind: "resize", horizontal: -1, vertical: -1 });
  assert.deepEqual(getEditorImagePointerInteraction(200, 120, 196, 4), { kind: "resize", horizontal: 1, vertical: -1 });
  assert.deepEqual(getEditorImagePointerInteraction(200, 120, 4, 116), { kind: "resize", horizontal: -1, vertical: 1 });
  assert.deepEqual(getEditorImagePointerInteraction(200, 120, 196, 116), { kind: "resize", horizontal: 1, vertical: 1 });
  assert.deepEqual(getEditorImagePointerInteraction(200, 120, 100, 60), { kind: "drag" });
});

test("editor image wrapping flips to the side nearest the image", () => {
  assert.equal(getEditorImageFloatSideForVisualLeft(800, 200, 200), "left");
  assert.equal(getEditorImageFloatSideForVisualLeft(800, 200, 500), "right");
  assert.equal(getEditorImageInlineOffsetForVisualLeft(800, 200, "left", 160), 160);
  assert.equal(getEditorImageInlineOffsetForVisualLeft(800, 200, "right", 500), 100);
});

test("editor image vertical offset allows moving above the insertion point", () => {
  assert.equal(clampEditorImageVerticalOffset(-240, -5_000, 5_000), -240);
  assert.equal(clampEditorImageVerticalOffset(-6_000, -5_000, 5_000), -5_000);
});

test("editor image storage budget shrinks near the document save limit", () => {
  assert.equal(getEditorImageStorageBudgetForDocumentBytes(1_000), 8_388_608);
  assert.equal(getEditorImageStorageBudgetForDocumentBytes(11_800_000), 532_380);
  assert.equal(getEditorImageStorageBudgetForDocumentBytes(12_100_000), 524_288);
});
